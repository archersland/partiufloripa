const assert=require('node:assert/strict');
const ux=require('./event-ux.js');
const today='2026-11-02';
const items=[{date:'2026-10-31'},{date:'2026-11-02'},{date:'2026-12-06'}];
assert.deepEqual(ux.months(items),['2026-10','2026-11','2026-12']);
assert.equal(ux.initialMonth(items,today),'2026-11');
assert.equal(ux.initialMonth(items,'2026-11-30'),'2026-11');
assert.equal(ux.initialMonth(items,'2027-01-01'),'2026-12');
assert.equal(ux.matchesDate(items[1],'today',today),true);
assert.equal(ux.matchesDate(items[0],'today',today),false);
assert.equal(ux.matchesDate({date:'2026-11-03'},'tomorrow',today),true);
assert.deepEqual(ux.weekendDates('2026-11-02'),['2026-11-07','2026-11-08']);
assert.deepEqual(ux.weekendDates('2026-11-07'),['2026-11-07','2026-11-08']);
assert.deepEqual(ux.weekendDates('2026-11-08'),['2026-11-08']);
assert.equal(ux.matchesDate({date:'2026-11-08'},'weekend',today),true);
assert.equal(ux.validDate('2026-02-30'),false);
assert.equal(ux.validTime('25:15'),false);
const event={id:'evt-012345abcdef',title:'Show, teste; Floripa',date:'2026-11-07',time:'21:30',venue:'Teatro\nSC',region:'Centro',source:'https://example.org/evento'};
const text=ux.calendarFile(event,new Date('2026-11-02T12:00:00Z'));
assert(text.includes('DTSTART;TZID=America/Sao_Paulo:20261107T213000'));
assert(text.includes('DTSTAMP:20261102T120000Z'));
assert(text.includes('SUMMARY:Show\\, teste\\; Floripa'));
assert(text.includes('LOCATION:Teatro\\nSC\\, Centro\\, Florianópolis'));
assert(text.includes('Fonte: https://example.org/evento'));
assert.equal(ux.calendarFile({...event,time:''}),null);
console.log('Event UX tests passed: dynamic dates, weekend filters and .ics content');
