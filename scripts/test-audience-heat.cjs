const assert=require('node:assert/strict');
const heat=require('./audience-heat.js');
const evidence={sourceUrl:'https://example.org/venue',reviewedAt:'2026-11-02'};
const registry={venues:[{name:'Small',capacity:{people:20,...evidence}},{name:'Big',capacity:{people:3000,...evidence}}]};
const event=(venue,id='a',extra={})=>({venue,id,date:'2026-11-04',time:'20:00',...extra});
assert.equal(heat.resolve(event('Small'),registry).people,20);
assert.equal(heat.resolve(event('Big'),registry).people,3000);
assert.equal(heat.resolve(event('Unknown'),registry).people,null);
assert.equal(heat.resolve(event('Big','a',{audience:{expected:1200,...evidence}}),registry).people,1200);
assert.equal(heat.resolve(event('Big','a',{audience:{expected:0,...evidence}}),registry).people,0);
assert.equal(heat.resolve(event('Big','a',{audience:{expected:1200}}),registry).people,3000);
assert.equal(heat.resolve(event('Big','a',{audience:{expected:-1,...evidence}}),registry).people,3000);
assert.equal(heat.resolve(event('Big','a',{audience:{expected:5000,...evidence}}),registry).people,3000);
assert.equal(heat.resolve(event('Big','a',{audience:{capacity:6000,expected:5000,...evidence}}),registry).people,5000);
assert.equal(heat.aggregate([event('Small'),event('Big','b')],registry).people,3020);
assert.equal(heat.aggregate([event('Big'),event('Big','b')],registry).people,3000);
assert.equal(heat.aggregate([event('Big'),event('Big')],registry).people,3000);
const session=(id,time,endTime,expected)=>event('Big',id,{time,endTime,audience:{expected,...evidence}});
assert.equal(heat.aggregate([session('a','19:00','20:00',800),session('b','20:00','21:00',1200)],registry).people,1200);
assert.equal(heat.aggregate([session('a','19:00','21:00',800),session('b','20:00','22:00',1200)],registry).people,2000);
assert.equal(heat.aggregate([session('a','23:00','01:00',800),session('b','23:30','00:30',1200)],registry).people,2000);
assert.equal(heat.aggregate([event('Unknown')],registry).people,null);
assert.equal(heat.aggregate([event('Small'),event('Unknown','b')],registry).unknown,1);
assert.equal(heat.resolve(event('Small'),{venues:[{name:'Small',capacity:{people:20,...evidence,status:'disputed'}}]}).people,null);
assert.match(heat.describe(event('Small'),registry),/20/);
assert.match(heat.describe(event('Big','a',{audience:{expected:1200,...evidence}}),registry),/previsto/i);
assert.equal(heat.visualWeight(null),0,'unknown reference must not render heat');
assert.equal(heat.visualWeight(0),0,'documented expected zero must not render heat');
assert.equal(heat.visualWeight(-1),0,'negative values must not render heat');
assert.equal(heat.visualWeight(NaN),0,'non-finite values must not render heat');
assert.equal(heat.visualWeight(10000),heat.max,'reference maximum');
assert.equal(heat.visualWeight(20000),heat.max,'visual saturation is capped');
const weights=[20,138,520,906,3000,10000].map(x=>heat.visualWeight(x));
assert(weights[0]>0.18*heat.max,'small valid event must be perceptible');
assert(weights.every((x,i)=>i===0||x>weights[i-1]),'larger audience must produce stronger heat');
assert(heat.visualWeight(906)===heat.visualWeight(906),'intensity must be stable across dates');
const haloCases=[[20,30],[138,33],[520,37],[906,40],[3000,50],[10000,68],[20000,68],[null,42],[0,42],[-1,42]];
for(const [people,pixels] of haloCases)assert.equal(heat.haloDiameter(people),pixels,'halo diameter '+people);
assert([20,138,520,906,3000,10000].map(x=>heat.haloDiameter(x)).every((v,i,a)=>i===0||v>a[i-1]),'larger known audience must have larger area');
assert(heat.haloDiameter(906)<128&&heat.haloDiameter(10000)<128,'no neighborhood-scale overspill');
console.log('Audience heat: capacity, forecasts, evidence, unknowns, deduplication, overlapping sessions and localized halo sizes OK');
