const assert=require("node:assert/strict");
const {selectHome}=require("./home-layout.js");
const e=(id,date,time="21:00")=>({id,date,time,venue:"Local demonstrativo"});
const d="2026-11-03";
const source=[e("old","2026-10-31"),e("late","2026-11-03","23:00"),e("early","2026-11-03","18:00"),e("next","2026-11-04"),e("later","2026-12-02")];
const snapshot=JSON.stringify(source);
let v=selectHome(source,{today:d,month:"2026-11"});
assert.equal(v.featured.id,"early","earliest event today is featured");
assert.deepEqual(v.upcoming.map(x=>x.id),["late","next"],"next list remains in month and no duplicate featured");
assert.equal(v.title,"Destaque do dia");
assert.equal(JSON.stringify(source),snapshot,"no input mutation");
v=selectHome(source,{today:d,mode:"tomorrow",month:"2026-11"});
assert.equal(v.featured.id,"early","date selection must be applied by event filter prior to projection");
const tomorrow=source.filter(x=>x.date==="2026-11-04");
v=selectHome(tomorrow,{today:d,mode:"tomorrow",month:"2026-11"});
assert.equal(v.featured.id,"next");
assert.equal(v.upcoming.length,0);
assert.equal(v.title,"Destaque de amanhã");
v=selectHome([],{today:d,mode:"today",month:"2026-11"});
assert.equal(v.featured,null);
assert.deepEqual(v.upcoming,[]);
v=selectHome([e("old","2026-11-02"),e("future","2026-11-07")],{today:d,month:"2026-11"});
assert.equal(v.featured.id,"future","today with no event falls back only when no date filter");
assert.equal(v.upcoming.length,0);
v=selectHome([e("sat","2026-11-07"),e("sun","2026-11-08")],{today:d,mode:"weekend"});
assert.equal(v.title,"Neste fim de semana");
assert.deepEqual(v.upcoming.map(x=>x.id),["sun"]);
v=selectHome([e("jan","2027-01-01")],{today:"2026-12-30",month:"2026-12"});
assert.equal(v.featured.id,"jan");
assert.equal(v.upcoming.length,0);
console.log("Dark home projection passed: featured/next isolation, empty dates, weekend, future-only and immutability");
