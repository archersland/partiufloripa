const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const hours=require('./venue-hours.js');
const registry=JSON.parse(fs.readFileSync(path.join(root,'data/venue-hours.json'),'utf8'));
const venues=JSON.parse(fs.readFileSync(path.join(root,'data/venues.json'),'utf8'));
const dates={tue:'2026-11-03',wed:'2026-11-04',fri:'2026-11-06',sun:'2026-11-08',mon:'2026-11-09'};
assert.equal(hours.weekday(dates.tue),2);
assert.equal(hours.weekday(dates.sun),0);
assert.equal(hours.weekday('2026-02-29'),null);
const status=(id,date,today=dates.tue)=>hours.status(id,registry,date,today);
assert.equal(status('ori-boteco-centro',dates.tue).status,'open');
assert.equal(status('ori-boteco-centro',dates.sun).status,'open');
assert.equal(status('chopp-do-gus-corrego-grande',dates.tue).status,'open');
assert.equal(status('chopp-do-gus-corrego-grande',dates.mon).status,'closed');
assert.equal(status('scuna-bar-club',dates.fri).status,'open');
assert.equal(status('scuna-bar-club',dates.tue).status,'closed');
assert.equal(status('berlin-floripa',dates.tue).status,'open');
assert.equal(status('no-class',dates.wed).status,'unknown','special-event nights outside regular schedule cannot be labelled closed');
assert.equal(status('unknown-venue',dates.tue).status,'unknown');
assert.equal(status('bugio-centro',dates.tue).status,'unknown');
assert.equal(status('scuna-bar-club','invalid').status,'unknown');
assert.equal(status('scuna-bar-club',dates.tue,'2027-03-20').status,'unknown','stale source must not determine status');
const conflict={venues:[{id:'test',openDays:[2],closedDays:[2],sourceUrl:'https://example.org',reviewedAt:dates.tue}]};
assert.equal(hours.status('test',conflict,dates.tue,dates.tue).status,'unknown');
const bad={venues:[{id:'test',openDays:[2],closedDays:[1],sourceUrl:'http://example.org',reviewedAt:dates.tue}]};
assert.equal(hours.status('test',bad,dates.tue,dates.tue).status,'unknown');
const ids=new Set();
for(const h of registry.venues){
 assert(!ids.has(h.id),'duplicate schedule '+h.id);ids.add(h.id);
 assert(venues.venues.some(v=>v.id===h.id),'unknown venue '+h.id);
 assert(hours.validDays(h.openDays)&&hours.validDays(h.closedDays));
 assert(!h.openDays.some(d=>h.closedDays.includes(d)),'conflicting days '+h.id);
 assert(h.sourceUrl.startsWith('https://'),'source required '+h.id);
 assert(hours.validDate(h.reviewedAt),'review date required '+h.id);
 assert(h.hoursText,'human readable hours '+h.id);
}
assert.equal(registry.venues.length,5);
console.log('Venue opening-day tests passed: evidence, weekday, unknown and stale fallback');
